"""Build no-op stand-ins for the desktop GUI libraries VST3 plug-ins link
for their editors (libGL, libX11, libXext, libXrandr, libXcursor...).

The MPC has none of them, so a plug-in that lists one in NEEDED fails to
dlopen even though a headless host never opens its editor. Each stub keeps
the real library's soname and exports every function the real one does,
all returning 0, so the dynamic linker is satisfied and any accidental call
fails softly (XOpenDisplay gives NULL: no display).

Run inside the base's build image from the repository root:
    python3 tools/vst_probe/make_stubs.py build/vst_probe/stubs
It installs the real Debian libraries in the container only to read their
export lists; nothing from them is copied.
"""
from pathlib import Path
import subprocess
import sys

# Debian package -> sonames whose exports are mirrored.
PACKAGES = {
    "libgl1": ["libGL.so.1"],
    "libx11-6": ["libX11.so.6"],
    "libxext6": ["libXext.so.6"],
    "libxrandr2": ["libXrandr.so.2"],
    "libxcursor1": ["libXcursor.so.1"],
    "libxrender1": ["libXrender.so.1"],
    "libxinerama1": ["libXinerama.so.1"],
    "libxi6": ["libXi.so.6"],
    "libxfixes3": ["libXfixes.so.3"],
}


def run(*command, **kwargs):
    return subprocess.run(command, check=True, text=True, **kwargs)


def exported_functions(library):
    table = run("readelf", "-W", "--dyn-syms", library, capture_output=True).stdout
    names = set()
    for line in table.splitlines():
        fields = line.split()
        # Num: Value Size Type Bind Vis Ndx Name
        if len(fields) >= 8 and fields[3] == "FUNC" and fields[6] != "UND" and fields[4] in ("GLOBAL", "WEAK"):
            names.add(fields[7].split("@")[0])
    return sorted(names)


def find_library(soname):
    for folder in ("/usr/lib/aarch64-linux-gnu", "/lib/aarch64-linux-gnu", "/usr/lib"):
        path = Path(folder) / soname
        if path.exists():
            return path
    raise SystemExit(f"{soname} not found after installing its package")


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "build/vst_probe/stubs")
    out.mkdir(parents=True, exist_ok=True)
    run("apt-get", "update", "-qq", stdout=subprocess.DEVNULL)
    run("apt-get", "install", "-y", "-qq", "--no-install-recommends", *PACKAGES, stdout=subprocess.DEVNULL)
    for sonames in PACKAGES.values():
        for soname in sonames:
            functions = exported_functions(find_library(soname))
            source = out / (soname + ".c")
            source.write_text("/* Generated by tools/vst_probe/make_stubs.py: no-op " + soname + " */\n"
                              + "".join(f"long {name}(void) {{ return 0; }}\n" for name in functions))
            run("cc", "-O1", "-shared", "-fPIC", "-fno-builtin", "-w", f"-Wl,-soname,{soname}",
                "-o", str(out / soname), str(source))
            source.unlink()
            print(f"{soname}: {len(functions)} functions")


if __name__ == "__main__":
    main()
