"""The panel's type as a C header: National Park (SIL OFL 1.1; `make fonts` fetches it), a variable font, at the
sizes and weights the panel uses, anti-aliased:
  np_title    27 px, 800  page titles
  np_wheel    20 px, 800  the wheel's choice
  np_value    17 px, 700  knob values
  np_value_s  13 px, 700  knob values too wide for np_value
  np_name     12 px, 600  the preset's name
  np_label    11 px, 800  knob labels, labels in the pictures
  np_small    11 px, 600  units, the page number, knob values too wide for np_value_s

    python3 fonts.py NationalPark.ttf fonts.h

Printable ASCII; each glyph an 8-bit coverage map of its ink (which may reach past its advance), one row per pixel
of the font's height. Needs Pillow with FreeType."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font_path, output = map(Path, sys.argv[1:])


def face(name, size, weight):
    font = ImageFont.truetype(str(font_path), size)
    font.set_variation_by_axes([weight])
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, pixels = [], []
    for code in range(32, 127):
        ch = chr(code)
        advance = round(font.getlength(ch))
        left, _, right, _ = font.getbbox(ch) if ch != ' ' else (0, 0, advance, 0)
        x0, x1 = min(0, left), max(advance, right)
        width = max(1, x1 - x0)
        image = Image.new('L', (width, height))
        ImageDraw.Draw(image).text((-x0, 0), ch, font=font, fill=255)
        glyphs.append((len(pixels), width, advance, x0))
        pixels.extend(image.getdata())
    return name, glyphs, pixels, height, ascent


FACES = [
    face('np_title', 27, 800),
    face('np_wheel', 20, 800),
    face('np_value', 17, 700),
    face('np_value_s', 13, 700),
    face('np_name', 12, 600),
    face('np_label', 11, 800),
    face('np_small', 11, 600),
]

parts = ['// Generated by experiments/lo-fly/fonts.py from National Park (SIL OFL 1.1). Do not edit.']
for name, glyphs, pixels, height, ascent in FACES:
    parts.append(f'static constexpr Glyph {name}_glyphs[] = {{' + ','.join('{%d,%d,%d,%d}' % g for g in glyphs) + '};')
    parts.append(f'static constexpr unsigned char {name}_pixels[] = {{' + ','.join(map(str, pixels)) + '};')
    parts.append(f'static constexpr Font {name}_font {{{name}_glyphs, {name}_pixels, {height}, {ascent}}};')
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('\n'.join(parts) + '\n')
